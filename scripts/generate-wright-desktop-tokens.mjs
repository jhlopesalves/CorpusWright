#!/usr/bin/env node
/** Derive desktop CSS from the Wright distribution's tokens.json. */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { block, declaration, typeDeclarations } from "./wright-token-css.mjs";

const [input, flag] = process.argv.slice(2);
if (!input || process.argv.length > 4 || (flag && flag !== "--check")) {
  throw new Error("Usage: node scripts/generate-wright-desktop-tokens.mjs <Wright/tokens.json> [--check]");
}

const output = new URL("../apps/desktop/src/styles/foundations/wright-tokens.css", import.meta.url);
const source = readFileSync(input);
const sourceHash = createHash("sha256").update(source).digest("hex");
const design = JSON.parse(source);
const themeTokens = [...design.color.tokens, ...design.shadow.tokens];
const shared = [
  ...[...design.spacing.tokens, ...design.radius.tokens, ...design.size.tokens].map(token => declaration(token)),
  ...Object.entries(design.type.families).map(([name, value]) => declaration({ name: `font-${name}`, value })),
  ...typeDeclarations(design.type.groups),
  // Wright specifies motion in its README.
  "--motion-fast: 140ms;",
  "--motion-ui: 240ms;",
  "--motion-state: 420ms;",
  "--motion-easing: cubic-bezier(0.2, 0, 0, 1);",
];

const css = [
  `/* Generated by scripts/generate-wright-desktop-tokens.mjs from Wright/tokens.json (SHA-256 ${sourceHash}). */`,
  block(':root, [data-theme="wright-light"], [data-theme="wright-dark"]', shared),
  ...["light", "dark"].map(variant => block(
    `[data-theme="wright-${variant}"]`,
    themeTokens.map(token => declaration(token, variant)),
  )),
].join("\n\n") + "\n";

if (flag === "--check") {
  if (readFileSync(output, "utf8") !== css) throw new Error("Desktop Wright token stylesheet needs regeneration.");
} else {
  writeFileSync(output, css);
}
