#!/usr/bin/env node
/** Derive public-site CSS from the Wright distribution's tokens.json. */
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { block, declaration, typeDeclarations } from "./wright-token-css.mjs";

const [input, flag] = process.argv.slice(2);
if (!input || process.argv.length > 4 || (flag && flag !== "--check")) {
  throw new Error("Usage: node scripts/generate-wright-site-tokens.mjs <Wright/tokens.json> [--check]");
}

const output = new URL("../docs/assets/wright-tokens.css", import.meta.url);
const source = readFileSync(input, "utf8");
const sourceHash = createHash("sha256").update(source).digest("hex");
const design = JSON.parse(source);
const themeTokens = [...design.color.tokens, ...design.shadow.tokens];
const sharedTokens = [...design.spacing.tokens, ...design.radius.tokens, ...design.size.tokens];

// Adobe reserves its original family names. The local webfont subsets use
// their own family names while retaining the upstream outlines and licences.
const localFaces = new Map([
  ["fonts/Manrope-Variable.ttf", ["Manrope", "Manrope.woff2"]],
  ["fonts/SourceSans3-Variable.ttf", ["Wright Reading", "WrightReading.woff2"]],
  ["fonts/SourceSans3-Italic-Variable.ttf", ["Wright Reading", "WrightReading-Italic.woff2"]],
]);
const faces = design.type.fonts.map(({ file, weight, style }) => {
  const [family, localFile] = localFaces.get(file);
  return { family, localFile, weight, style };
});
faces.push({ family: "Wright Code", localFile: "WrightCode.woff2", weight: "200 900", style: "normal" });

function face({ family, localFile, weight, style }) {
  return [
    "@font-face {",
    `  font-family: "${family}";`,
    `  src: url("fonts/wright/${localFile}") format("woff2");`,
    `  font-weight: ${weight};`,
    `  font-style: ${style};`,
    "  font-display: swap;",
    "}",
  ].join("\n");
}

const familyDeclarations = Object.entries(design.type.families).map(([name, family]) =>
  declaration({
    name: `font-${name}`,
    value: family.replace("Source Sans 3", "Wright Reading").replace("Source Code Pro", "Wright Code"),
  }),
);

const light = themeTokens.map((token) => declaration(token, "light"));
const dark = themeTokens
  .filter(({ value }) => typeof value !== "string" && value.light !== value.dark)
  .map((token) => declaration(token, "dark"));

const css = [
  `/* Generated by scripts/generate-wright-site-tokens.mjs from Wright/tokens.json (SHA-256 ${sourceHash}). */`,
  ...faces.map(face),
  block(":root", [...light, ...sharedTokens.map((token) => declaration(token)), ...familyDeclarations, ...typeDeclarations(design.type.groups)]),
  block(':root[data-theme="dark"]', dark),
  `@media (prefers-color-scheme: dark) {\n${block(":root:not([data-theme])", dark, "  ")}\n}`,
].join("\n\n") + "\n";

if (flag === "--check") {
  if (readFileSync(output, "utf8") !== css) throw new Error("Wright token stylesheet needs regeneration.");
} else {
  writeFileSync(output, css);
}
